import fs from 'node:fs';
import { geoMercator, geoPath, geoCentroid, geoContains, geoBounds } from 'd3-geo';

// Source snapshots are retained so rebuilding never requires the network.
const source = JSON.parse(fs.readFileSync('scripts/data/thailand-provinces.source.geojson','utf8'));
const names = JSON.parse(fs.readFileSync('scripts/data/thailand-province-names.source.json','utf8'));
const normalize = name => name.replace(/ Province$/,'').toUpperCase().replace(/[^A-Z]/g,'');
if (source.features.length!==77 || names.length!==77) throw Error('Expected all 77 Thai provinces, including Bangkok and Bueng Kan');
function orient(ring,hole) {
  const area=ring.reduce((sum,p,i)=>{const q=ring[(i+1)%ring.length];return sum+p[0]*q[1]-q[0]*p[1];},0);
  return (hole ? area<0 : area>0) ? [...ring].reverse() : ring;
}
const features=source.features.map(feature=>({ ...feature, geometry:{type:'MultiPolygon',coordinates:
  (feature.geometry.type==='Polygon'?[feature.geometry.coordinates]:feature.geometry.coordinates)
    .map(polygon=>polygon.map((ring,i)=>orient(ring,i>0))),
} }));
const projection=geoMercator().fitExtent([[35,35],[965,635]],{type:'FeatureCollection',features});
const path=geoPath(projection).digits(2);
const known={ 'TH-10':[100.5018,13.7563], 'TH-50':[98.9853,18.7883], 'TH-83':[98.3381,7.8804] };
function anchor(feature) {
  const preferred=known[feature.properties.shapeISO]??geoCentroid(feature);
  if (geoContains(feature,preferred)) return preferred;
  const [[west,south],[east,north]]=geoBounds(feature);
  const candidates=[];
  for(let x=1;x<40;x++) for(let y=1;y<40;y++) {
    const p=[west+(east-west)*x/40,south+(north-south)*y/40];
    if(geoContains(feature,p)) candidates.push(p);
  }
  candidates.sort((a,b)=>Math.hypot(a[0]-preferred[0],a[1]-preferred[1])-Math.hypot(b[0]-preferred[0],b[1]-preferred[1]));
  if(!candidates.length)throw Error('No interior label point: '+feature.properties.shapeName);
  return candidates[0];
}
const catalog=[];
const provinces=features.map((feature,index)=>{
  const code=feature.properties.shapeISO;
  if(!/^TH-\d{2}$/.test(code))throw Error('Invalid ISO province code');
  const entry=names.find(n=>normalize(n.name.en)===normalize(feature.properties.shapeName));
  if(!entry)throw Error('No bilingual name: '+feature.properties.shapeName);
  const coordinates=anchor(feature).map(v=>+v.toFixed(6));
  catalog.push({code,name:entry.name.en,thaiName:entry.name.th,localName:entry.name.th,
    capitalCode:entry.name.en.toUpperCase().replace(/[^A-Z0-9]+/g,'_'),capital:entry.name.en,coordinates});
  return {code,path:path(feature),label:projection(coordinates),bounds:path.bounds(feature),geometry:source.features[index].geometry};
});
catalog.sort((a,b)=>a.code.localeCompare(b.code));
fs.mkdirSync('public/assets/maps/thailand',{recursive:true});
fs.writeFileSync('public/assets/maps/thailand/provinces.json',JSON.stringify({type:'FeatureCollection',provinces}));
fs.writeFileSync('src/app/core/data/thailand-provinces.generated.ts',
  '// Generated by scripts/generate-thailand-map.mjs. See public/assets/maps/thailand/README.md for sources.\n'+
  'export interface ThailandProvince { code: string; name: string; thaiName: string; localName: string; capitalCode: string; capital: string; coordinates: [number, number]; }\n'+
  'export const THAILAND_PROVINCES: readonly ThailandProvince[] = '+JSON.stringify(catalog,null,2)+';\n');
console.log('Generated 77 Thai province boundaries and bilingual destinations.');
